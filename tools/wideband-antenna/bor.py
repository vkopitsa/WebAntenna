"""Body-of-revolution EFIE MoM (m = 0, PEC, free space) for axially symmetric antennas.

The surface is generated by rotating polylines in the (rho, z) half-plane about the z axis.
Unknowns: total axial current I(t) = 2*pi*rho*J_t, piecewise linear (triangles) along the
generating curve, Galerkin testing.  This is the thin-wire formulation with the exact ring
kernel, so fat cones, discs, tubes and junctions (>= 3 segments meeting at a node) all work.

  Z_mn = jwmu  sum  c_p c_q  int int T_p T_q (rho' rho'' I1 + z' z'' I0) dt dt'
       + 1/(jweps) sum (dT_p/dt)(dT_q/dt') int int I0 dt dt'
  I0 = 1/(2pi) int G dphi,  I1 = 1/(2pi) int cos(phi) G dphi,  G = exp(-jkR)/(4 pi R)

Static part of I0 = K(m) / (2 pi^2 D) exactly (complete elliptic integral, AGM); the log
singularity on a segment's own span is integrated analytically, the rest by Gauss and a
midpoint rule in phi (spectrally accurate for periodic integrands).
"""
import math
import numpy as np
from numba import njit, prange

C0 = 299792458.0
MU0 = 4e-7 * math.pi
EPS0 = 1.0 / (MU0 * C0 * C0)
ETA0 = MU0 * C0

def _gl(n):
    x, w = np.polynomial.legendre.leggauss(n)
    return (x + 1) / 2, w / 2

GQ_X, GQ_W = _gl(4)     # outer (observation) rule per segment
GH_X, GH_W = _gl(12)    # inner rule for near pairs
GS_X, GS_W = _gl(8)     # inner rule on each side of the observation point (self term)


@njit(cache=True, fastmath=False)
def _ellipk_comp(m1):
    """K(m) with m1 = 1 - m, via AGM; returns K."""
    a = 1.0
    b = math.sqrt(m1)
    for _ in range(40):
        an = 0.5 * (a + b)
        b = math.sqrt(a * b)
        a = an
        if abs(a - b) < 1e-15 * a:
            break
    return math.pi / (2.0 * a)


@njit(cache=True, fastmath=False)
def _kern(rho, z, rp, zp, k, D0sub):
    """Return (I0, I0 - I1) as complex numbers.  If D0sub > 0, the log singularity
    -ln(d)/(2 pi^2 D0sub) is removed from I0 (to be integrated analytically)."""
    dz = z - zp
    d2 = (rho - rp) ** 2 + dz * dz
    D2 = (rho + rp) ** 2 + dz * dz
    D = math.sqrt(D2)
    m1 = d2 / D2
    # static part of I0
    if m1 < 1e-300:
        stat = 0.0  # only reached with subtraction; handled by caller (never at d=0 exactly)
    else:
        K = _ellipk_comp(m1)
        stat = K / (2.0 * math.pi * math.pi * D)
        if D0sub > 0.0:
            stat += math.log(math.sqrt(d2)) / (2.0 * math.pi * math.pi * D0sub)
    # phi integrals by midpoint rule on [0, pi]
    q = math.sqrt(rho * rp)
    nphi = 10 + int(3.0 * k * q)
    if nphi > 400:
        nphi = 400
    h = math.pi / nphi
    sr = 0.0
    si = 0.0  # smooth part of I0: (exp(-jkR) - 1)/(4 pi R)
    tr = 0.0
    ti = 0.0  # (1 - cos phi) exp(-jkR)/(4 pi R)
    for i in range(nphi):
        ph = (i + 0.5) * h
        sh = math.sin(0.5 * ph)
        R = math.sqrt(d2 + 4.0 * rho * rp * sh * sh)
        kR = k * R
        c = math.cos(kR)
        s = math.sin(kR)
        if kR < 1e-6:
            sr += 0.0
            si += -k
        else:
            sr += (c - 1.0) / R
            si += -s / R
        omc = 2.0 * sh * sh
        tr += omc * c / R
        ti += -omc * s / R
    f = h / (math.pi * 4.0 * math.pi)  # (1/pi) * h * 1/(4 pi)
    I0 = complex(stat + sr * f, si * f)
    D01 = complex(tr * f, ti * f)
    return I0, D01


@njit(cache=True)
def _F0(x, L):
    a = L - x
    t1 = a * math.log(abs(a)) if abs(a) > 0 else 0.0
    t2 = x * math.log(abs(x)) if abs(x) > 0 else 0.0
    return t1 + t2 - L


@njit(cache=True)
def _hF1(v, x):
    if abs(v) == 0.0:
        return 0.0
    lv = math.log(abs(v))
    return 0.5 * v * v * lv - 0.25 * v * v + x * (v * lv - v)


@njit(cache=True)
def _F1(x, L):
    return _hF1(L - x, x) - _hF1(-x, x)


@njit(parallel=True, cache=True)
def blocks(r0, z0, r1, z1, near, k, gx, gw, hx, hw, sx, sw):
    S = r0.shape[0]
    M = np.zeros((S, S), np.complex128)
    B = np.zeros((2 * S, 2 * S), np.complex128)
    nq = gx.shape[0]
    for s in prange(S):
        Ls = math.hypot(r1[s] - r0[s], z1[s] - z0[s])
        trs = (r1[s] - r0[s]) / Ls
        tzs = (z1[s] - z0[s]) / Ls
        for sp in range(S):
            Lp = math.hypot(r1[sp] - r0[sp], z1[sp] - z0[sp])
            trp = (r1[sp] - r0[sp]) / Lp
            tzp = (z1[sp] - z0[sp]) / Lp
            m = 0j
            b00 = 0j
            b01 = 0j
            b10 = 0j
            b11 = 0j
            for i in range(nq):
                u = gx[i]
                wo = gw[i] * Ls
                rho = r0[s] + u * (r1[s] - r0[s])
                z = z0[s] + u * (z1[s] - z0[s])
                a0 = 0j  # int I0
                aA0 = 0j  # int KA
                aA1 = 0j  # int u' KA
                if s == sp:
                    D0 = 2.0 * rho
                    x = u * Ls
                    # left part [0, x] and right part [x, L]
                    for side in range(2):
                        if side == 0:
                            ua = 0.0
                            ub = u
                        else:
                            ua = u
                            ub = 1.0
                        for j in range(sx.shape[0]):
                            up = ua + (ub - ua) * sx[j]
                            wi = sw[j] * (ub - ua) * Ls
                            rp = r0[sp] + up * (r1[sp] - r0[sp])
                            zp = z0[sp] + up * (z1[sp] - z0[sp])
                            I0, D01 = _kern(rho, z, rp, zp, k, D0)
                            KA = I0 - trs * trp * D01
                            a0 += wi * I0
                            aA0 += wi * KA
                            aA1 += wi * up * KA
                    c = -1.0 / (2.0 * math.pi * math.pi * D0)
                    f0 = c * _F0(x, Ls)
                    f1 = c * _F1(x, Ls) / Ls
                    a0 += f0
                    aA0 += f0
                    aA1 += f1
                else:
                    if near[s, sp]:
                        qx = hx
                        qw = hw
                    else:
                        qx = gx
                        qw = gw
                    for j in range(qx.shape[0]):
                        up = qx[j]
                        wi = qw[j] * Lp
                        rp = r0[sp] + up * (r1[sp] - r0[sp])
                        zp = z0[sp] + up * (z1[sp] - z0[sp])
                        I0, D01 = _kern(rho, z, rp, zp, k, -1.0)
                        I1 = I0 - D01
                        KA = trs * trp * I1 + tzs * tzp * I0
                        a0 += wi * I0
                        aA0 += wi * KA
                        aA1 += wi * up * KA
                m += wo * a0
                b00 += wo * aA0
                b01 += wo * aA1
                b10 += wo * u * aA0
                b11 += wo * u * aA1
            M[s, sp] = m
            B[2 * s, 2 * sp] = b00
            B[2 * s, 2 * sp + 1] = b01
            B[2 * s + 1, 2 * sp] = b10
            B[2 * s + 1, 2 * sp + 1] = b11
    return M, B


# ----------------------------------------------------------------------------- geometry

class Geometry:
    """Polylines in the (rho, z) half-plane.  parts: list of (name, Nx2 array).  Endpoints that
    coincide are joined.  feed: dict(kind='frill', a, b, z) for a coax aperture on an annulus
    part named 'feed', or dict(kind='gap', at=(rho, z)) for a delta gap at a node."""

    def __init__(self, parts, feed, feed_point=None, loads=None):
        self.parts = [(n, np.asarray(p, float)) for n, p in parts]
        self.feed = feed
        self.loads = loads or []   # [((rho, z), Z or callable(f))] series loads at nodes
        if feed_point is None:
            feed_point = (feed["a"], feed["z"]) if feed["kind"] == "frill" else feed["at"]
        self.fp = np.asarray(feed_point, float)

    def extent(self):
        P = np.vstack([p for _, p in self.parts])
        return P[:, 0].max(), P[:, 1].min(), P[:, 1].max()


def _resample(poly, hfun):
    """Split a polyline into straight segments with local length ~ hfun(point)."""
    seg = np.diff(poly, axis=0)
    sl = np.hypot(seg[:, 0], seg[:, 1])
    s = np.concatenate([[0], np.cumsum(sl)])
    Ltot = s[-1]
    # integrate dn = ds / h on a fine grid
    ns = max(50, int(Ltot / 2e-4))
    ss = np.linspace(0, Ltot, ns + 1)
    pts = np.column_stack([np.interp(ss, s, poly[:, 0]), np.interp(ss, s, poly[:, 1])])
    h = hfun(pts)
    dn = np.concatenate([[0], np.cumsum(0.5 * (1 / h[1:] + 1 / h[:-1]) * np.diff(ss))])
    N = max(1, int(math.ceil(dn[-1] - 1e-9)))
    targets = np.linspace(0, dn[-1], N + 1)
    st = np.interp(targets, dn, ss)
    out = np.column_stack([np.interp(st, s, poly[:, 0]), np.interp(st, s, poly[:, 1])])
    # keep the original polyline corners exactly when the polyline is coarse (straight parts)
    out[0] = poly[0]
    out[-1] = poly[-1]
    return out


class Mesh:
    pass


def build_mesh(geo, f, per_lambda=20.0, h_feed=0.3e-3, grow=0.25, h_max=None, min_seg_feed=3):
    lam = C0 / f
    hl = lam / per_lambda
    if h_max is not None:
        hl = min(hl, h_max)
    fp = geo.fp

    def hfun(pts):
        d = np.hypot(pts[:, 0] - fp[0], pts[:, 1] - fp[1])
        return np.minimum(hl, h_feed + grow * d)

    nodes = []
    index = {}

    def node_id(p):
        key = (round(p[0] * 1e9), round(p[1] * 1e9))
        if key not in index:
            index[key] = len(nodes)
            nodes.append((p[0], p[1]))
        return index[key]

    segs = []
    tags = []
    parts = []
    for name, poly in geo.parts:
        cut = None
        for (p, _) in geo.loads:
            for i in range(len(poly) - 1):
                p0, p1 = poly[i], poly[i + 1]
                d = p1 - p0
                t = np.dot(np.asarray(p) - p0, d) / np.dot(d, d)
                if 1e-6 < t < 1 - 1e-6 and np.hypot(*(p0 + t * d - p)) < 1e-9:
                    cut = (i, np.asarray(p, float))
        if cut is None:
            parts.append((name, poly))
        else:
            i, p = cut
            parts.append((name, np.vstack([poly[: i + 1], p])))
            parts.append((name, np.vstack([p, poly[i + 1:]])))
    for name, poly in parts:
        if name == "feed":
            n = max(min_seg_feed, int(math.ceil(np.hypot(*(poly[-1] - poly[0])) / h_feed)))
            pts = np.column_stack([np.linspace(poly[0, 0], poly[-1, 0], n + 1), np.linspace(poly[0, 1], poly[-1, 1], n + 1)])
        else:
            pts = _resample(poly, hfun)
        ids = [node_id(p) for p in pts]
        for a, b in zip(ids[:-1], ids[1:]):
            if a != b:
                segs.append((a, b))
                tags.append(name)
    nodes = np.array(nodes)
    segs = np.array(segs)
    me = Mesh()
    me.nodes, me.segs, me.tags = nodes, segs, tags
    S = len(segs)
    me.r0 = nodes[segs[:, 0], 0].copy()
    me.z0 = nodes[segs[:, 0], 1].copy()
    me.r1 = nodes[segs[:, 1], 0].copy()
    me.z1 = nodes[segs[:, 1], 1].copy()
    me.L = np.hypot(me.r1 - me.r0, me.z1 - me.z0)
    # basis functions: at each node with >= 2 segments, pair the first with each other one
    att = [[] for _ in range(len(nodes))]
    for si, (a, b) in enumerate(segs):
        att[a].append(si)
        att[b].append(si)
    pieces = []  # (basis, seg, a0, a1)
    nb = 0
    me.node_basis = {}
    for c, lst in enumerate(att):
        if len(lst) < 2:
            continue
        A = lst[0]
        for Bs in lst[1:]:
            # into c along A
            if segs[A, 1] == c:
                pieces.append((nb, A, 0.0, 1.0))
            else:
                pieces.append((nb, A, -1.0, 1.0))
            # out of c along B
            if segs[Bs, 0] == c:
                pieces.append((nb, Bs, 1.0, -1.0))
            else:
                pieces.append((nb, Bs, 0.0, -1.0))
            me.node_basis.setdefault(c, []).append(nb)
            nb += 1
    me.nb = nb
    CA = np.zeros((nb, 2 * S))
    CP = np.zeros((nb, S))
    for (m, s, a0, a1) in pieces:
        CA[m, 2 * s] += a0
        CA[m, 2 * s + 1] += a1
        CP[m, s] += a1 / me.L[s]
    me.CA, me.CP, me.pieces = CA, CP, pieces
    # near-pair flags
    cr = 0.5 * (me.r0 + me.r1)
    cz = 0.5 * (me.z0 + me.z1)
    dist = np.hypot(cr[:, None] - cr[None, :], cz[:, None] - cz[None, :])
    me.near = dist < 1.5 * (me.L[:, None] + me.L[None, :])
    me.f = f
    me.geo = geo
    return me


def excitation(me):
    geo = me.geo
    V = np.zeros(me.nb)
    fd = geo.feed
    if fd["kind"] == "gap":
        key = None
        p = np.asarray(fd["at"])
        dd = np.hypot(me.nodes[:, 0] - p[0], me.nodes[:, 1] - p[1])
        c = int(np.argmin(dd))
        bl = me.node_basis[c]
        V[bl[0]] = 1.0
        return V
    a, b = fd["a"], fd["b"]
    lnba = math.log(b / a)
    for (m, s, a0, a1) in me.pieces:
        if me.tags[s] != "feed":
            continue
        L = me.L[s]
        tr = (me.r1[s] - me.r0[s]) / L
        acc = 0.0
        for u, w in zip(GH_X, GH_W):
            rho = me.r0[s] + u * (me.r1[s] - me.r0[s])
            acc += w * L * (a0 + a1 * u) * tr / (rho * lnba)
        V[m] += acc
    return V


class Solution:
    pass


def solve(me):
    k = 2 * math.pi * me.f / C0
    w = 2 * math.pi * me.f
    M, B = blocks(me.r0, me.z0, me.r1, me.z1, me.near, k, GQ_X, GQ_W, GH_X, GH_W, GS_X, GS_W)
    Z = 1j * w * MU0 * (me.CA @ B @ me.CA.T) + (1.0 / (1j * w * EPS0)) * (me.CP @ M @ me.CP.T)
    for (p, ZL) in me.geo.loads:
        dd = np.hypot(me.nodes[:, 0] - p[0], me.nodes[:, 1] - p[1])
        c = int(np.argmin(dd))
        zl = ZL(me.f) if callable(ZL) else ZL
        for m in me.node_basis.get(c, []):
            Z[m, m] += zl
    V = excitation(me)
    I = np.linalg.solve(Z, V.astype(complex))
    Iin = (V @ I)  # reaction with V = 1
    sol = Solution()
    sol.me, sol.I, sol.Z = me, I, 1.0 / Iin
    sol.k = k
    sol.Pin = 0.5 * np.real(np.conj(Iin))  # V = 1: P = 1/2 Re(V I*)
    return sol


def seg_currents(sol):
    """Current coefficients (a0 + a1 u) per segment: arrays c0, c1 of length S."""
    me = sol.me
    S = len(me.L)
    c0 = np.zeros(S, complex)
    c1 = np.zeros(S, complex)
    for (m, s, a0, a1) in me.pieces:
        c0[s] += a0 * sol.I[m]
        c1[s] += a1 * sol.I[m]
    return c0, c1


def far_N(sol, theta):
    """N_theta(theta) such that U = k^2 eta |N|^2 / (32 pi^2) for V = 1 at the port."""
    from scipy.special import j0, j1
    me = sol.me
    k = sol.k
    c0, c1 = seg_currents(sol)
    th = np.atleast_1d(theta)[:, None]
    N = np.zeros(th.shape[0], complex)
    ux, uw = GH_X, GH_W
    for u, w in zip(ux, uw):
        rho = me.r0 + u * (me.r1 - me.r0)
        z = me.z0 + u * (me.z1 - me.z0)
        tr = (me.r1 - me.r0) / me.L
        tz = (me.z1 - me.z0) / me.L
        I = c0 + c1 * u
        x = k * rho[None, :] * np.sin(th)
        ph = np.exp(1j * k * z[None, :] * np.cos(th))
        term = I[None, :] * ph * (tr[None, :] * np.cos(th) * 1j * j1(x) - tz[None, :] * np.sin(th) * j0(x))
        N += (w * me.L[None, :] * term).sum(axis=1)
    return N


def gain_dbi(sol, theta):
    N = far_N(sol, theta)
    U = sol.k ** 2 * ETA0 * np.abs(N) ** 2 / (32 * math.pi ** 2)
    return 10 * np.log10(np.maximum(4 * math.pi * U / sol.Pin, 1e-30))


def prad_check(sol, n=721):
    th = np.linspace(0, math.pi, n)
    N = far_N(sol, th)
    U = sol.k ** 2 * ETA0 * np.abs(N) ** 2 / (32 * math.pi ** 2)
    P = 2 * math.pi * np.trapz(U * np.sin(th), th)
    return P / sol.Pin


def swr(Z, z0=50.0):
    g = abs((Z - z0) / (Z + z0))
    return (1 + g) / (1 - g) if g < 1 else float("inf")


def run(geo, freqs, per_lambda=20.0, h_feed=0.3e-3, grow=0.25, pattern=True, el_deg=(0, 15, 30, 50), h_max=None):
    out = []
    for f in freqs:
        me = build_mesh(geo, f, per_lambda, h_feed, grow, h_max=h_max)
        sol = solve(me)
        row = dict(f=f, Z=sol.Z, swr=swr(sol.Z), n=me.nb)
        if pattern:
            th = np.radians(90 - np.asarray(el_deg, float))
            row["g"] = gain_dbi(sol, th)
            thf = np.radians(np.arange(0, 181, 2.0))
            gf = gain_dbi(sol, thf)
            row["gmax"] = gf.max()
            row["el_max"] = 90 - np.degrees(thf[np.argmax(gf)])
        out.append(row)
    return out
