// openEMS (FDTD) Python script export for printed antennas. The script builds the board, meshes it
// (edge thirds rule + smoothing), runs openEMS and post-processes like the official tutorials:
// S11, Zin, Smith, far-field cuts; results also saved to <name>_results.json / .csv / .png.
import type { AntennaDef, Design } from "./types";
import { minCopperFeature, type Pcb } from "./pcb";

const n = (x: number) => +(x * 1000).toPrecision(9); // metres → mm (script unit)

export function toOpenEMS(def: AntennaDef, design: Design, name = def.id): string {
  const p = design.pcb;
  if (!p) throw new Error("openEMS export is only available for printed antennas");
  const fmin = Math.min(...design.sweeps.map((s) => s.start)), fmax = Math.max(...design.sweeps.map((s) => s.stop));
  const rects = p.rects.map((q) => `    ("${q.layer}", ${n(q.x0)}, ${n(q.y0)}, ${n(q.x1)}, ${n(q.y1)}),  # ${q.label}`).join("\n");
  const polys = (p.polys ?? []).map((q) => `    ("${q.layer}", [${q.pts.map(([x, y]) => `(${n(x)}, ${n(y)})`).join(", ")}]),  # ${q.label}`).join("\n");
  return `# -*- coding: utf-8 -*-
"""
${def.name} — openEMS FDTD model generated by Antenna Generator.

Run:   python3 ${name}_openems.py            (add --no-show on a headless machine, --post to re-plot only)
Needs: openEMS + CSXCAD Python modules (https://docs.openems.de), numpy, matplotlib.
Units: mm. Board in the xy plane, bottom copper at z = 0, top copper at z = h.
"""
import os, sys, json, tempfile
import numpy as np
import matplotlib
if "--no-show" in sys.argv:
    matplotlib.use("Agg")
import matplotlib.pyplot as plt
from CSXCAD import ContinuousStructure
from openEMS import openEMS
from openEMS.physical_constants import C0, EPS0

NAME = "${name}"
SIM_PATH = os.path.join(tempfile.gettempdir(), "antgen_" + NAME)
POST_ONLY = "--post" in sys.argv
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), NAME)  # results are saved next to this script

# ---- design data (from the generator) ----
f_design = ${design.f}          # Hz, centre of band 1
f_min, f_max = ${fmin}, ${fmax}  # Hz, simulated span
bands = ${JSON.stringify(design.sweeps.map((s) => [s.start, s.stop]))}
eps_r, tan_d = ${p.er}, ${p.tanD}
h = ${n(p.h)}                    # substrate thickness
board = (${n(p.board.x0)}, ${n(p.board.y0)}, ${n(p.board.x1)}, ${n(p.board.y1)})  # x0, y0, x1, y1
copper = [  # (layer, x0, y0, x1, y1)
${rects}
]
copper_polys = [  # (layer, [(x, y), ...]): diagonal traces, staircased by the mesh
${polys}
]
port_start = [${p.port.start.map(n).join(", ")}]
port_stop = [${p.port.stop.map(n).join(", ")}]
port_dir, port_R = "${p.port.dir}", ${p.port.R}

# ---- FDTD setup ----
f0 = (f_min + f_max) / 2
fc = max((f_max - f_min) / 2 * 1.3, 0.25 * f0)       # Gaussian 20 dB corner
FDTD = openEMS(NrTS=200000, EndCriteria=1e-5)  # −50 dB: cleaner Zin than −40 dB
FDTD.SetGaussExcite(f0, fc)
FDTD.SetBoundaryCond(["MUR"] * 6)
CSX = ContinuousStructure()
FDTD.SetCSX(CSX)
mesh = CSX.GetGrid()
mesh.SetDeltaUnit(1e-3)

lam_min = C0 / (f0 + fc) / 1e-3                        # mm, shortest wavelength in the excitation
res_air = lam_min / 20
res_sub = lam_min / 20 / np.sqrt(eps_r)
min_feature = ${n(minFeature(p))}
edge = min(res_sub / 2, max(min_feature / 3, h / 2))   # metal edge resolution
air = C0 / max(f_min, f0 - fc) / 1e-3 / 2              # λ/2 air margin at the low end (λ/4 gave −0.4 dB on a reference dipole)

# substrate (loss as conductivity at f0)
sub = CSX.AddMaterial("substrate", epsilon=eps_r, kappa=2 * np.pi * f0 * EPS0 * eps_r * tan_d)
sub.AddBox([board[0], board[1], 0], [board[2], board[3], h], priority=0)
mesh.AddLine("z", np.linspace(0, h, 5))

for i, (layer, x0, y0, x1, y1) in enumerate(copper):
    z = h if layer == "top" else 0
    m = CSX.AddMetal(f"cu{i}_{layer}")
    m.AddBox([x0, y0, z], [x1, y1, z], priority=10)
    FDTD.AddEdges2Grid(dirs="xy", properties=m, metal_edge_res=edge)
for i, (layer, pts) in enumerate(copper_polys):
    z = h if layer == "top" else 0
    m = CSX.AddMetal(f"cupoly{i}_{layer}")
    m.AddPolygon([[q[0] for q in pts], [q[1] for q in pts]], "z", z, priority=10)
    xs, ys = [q[0] for q in pts], [q[1] for q in pts]
    # vertex lines plus a fill every min_feature/2, so the staircase of a diagonal strip stays connected
    mesh.AddLine("x", xs + list(np.arange(min(xs), max(xs), min_feature / 2)))
    mesh.AddLine("y", ys + list(np.arange(min(ys), max(ys), min_feature / 2)))

port = FDTD.AddLumpedPort(1, port_R, port_start, port_stop, port_dir, 1.0, priority=5, edges2grid="xy")

mesh.AddLine("x", [board[0] - air, board[2] + air])
mesh.AddLine("y", [board[1] - air, board[3] + air])
mesh.AddLine("z", [-air, h + air])
mesh.SmoothMeshLines("x", res_air, 1.4)
mesh.SmoothMeshLines("y", res_air, 1.4)
mesh.SmoothMeshLines("z", res_air, 1.4)
nf2ff = FDTD.CreateNF2FFBox()

if not POST_ONLY:
    print("mesh cells:", mesh.GetQtyLines("x"), "x", mesh.GetQtyLines("y"), "x", mesh.GetQtyLines("z"))
    FDTD.Run(SIM_PATH, cleanup=True, verbose=0)

# ---- post-processing ----
f = np.linspace(f_min, f_max, 401)
port.CalcPort(SIM_PATH, f)
s11 = port.uf_ref / port.uf_inc
s11_dB = 20 * np.log10(np.abs(s11))
Zin = port.uf_tot / port.if_tot
i_best = int(np.argmin(s11_dB))
f_res = f[i_best]
print(f"best match {f_res/1e6:.2f} MHz, S11 {s11_dB[i_best]:.1f} dB, Zin {Zin[i_best].real:.1f}{Zin[i_best].imag:+.1f}j Ohm")

# Resonances: zero crossings of Im(Zin)
res = [f[k] - Zin[k].imag * (f[k + 1] - f[k]) / (Zin[k + 1].imag - Zin[k].imag) for k in range(len(f) - 1) if Zin[k].imag * Zin[k + 1].imag < 0]
print("resonances (MHz):", ", ".join(f"{x/1e6:.1f}" for x in res))

# Far field. Dmax / Prad need the whole sphere (openEMS integrates over the requested angles).
centre = [(board[0] + board[2]) / 2 * 1e-3, (board[1] + board[3]) / 2 * 1e-3, h / 2 * 1e-3]  # metres (NF2FF works in SI units)
sph = nf2ff.CalcNF2FF(SIM_PATH, [f_design], np.arange(0.0, 180.1, 5.0), np.arange(0.0, 360.0, 5.0), center=centre, outfile="nf2ff_sphere.h5", read_cached=False)
Emax, Dmax = np.max(sph.E_norm[0]), float(sph.Dmax[0])
theta = np.arange(-180.0, 180.5, 2.0)
cut = nf2ff.CalcNF2FF(SIM_PATH, [f_design], theta, [0.0, 90.0], center=centre, outfile="nf2ff_cuts.h5", read_cached=False)
gain_cut = 20 * np.log10(np.maximum(cut.E_norm[0], 1e-30) / Emax) + 10 * np.log10(Dmax)
az = nf2ff.CalcNF2FF(SIM_PATH, [f_design], [90.0], np.arange(0.0, 360.5, 2.0), center=centre, outfile="nf2ff_az.h5", read_cached=False)
gain_az = 20 * np.log10(np.maximum(np.ravel(az.E_norm[0]), 1e-30) / Emax) + 10 * np.log10(Dmax)
k0 = int(np.argmin(abs(f - f_design)))
eff = float(sph.Prad[0] / port.P_acc[k0])
print(f"directivity at {f_design/1e6:.2f} MHz: {10*np.log10(Dmax):.2f} dBi, radiation efficiency {100*eff:.0f} %, gain {10*np.log10(Dmax*eff):.2f} dBi")

out = {"f": f.tolist(), "s11_db": s11_dB.tolist(), "zin_re": Zin.real.tolist(), "zin_im": Zin.imag.tolist(),
       "f_res": f_res, "resonances": res, "dmax_dbi": 10 * np.log10(Dmax), "efficiency": eff, "theta": theta.tolist(),
       "cut_xz": gain_cut[:, 0].tolist(), "cut_yz": gain_cut[:, 1].tolist(), "cut_xy": gain_az.tolist()}
with open(OUT + "_results.json", "w") as fh:
    json.dump(out, fh)
np.savetxt(OUT + "_s11.csv", np.c_[f, s11_dB, Zin.real, Zin.imag], delimiter=",", header="f_Hz,S11_dB,Re_Zin,Im_Zin", comments="")

fig, ax = plt.subplots(2, 2, figsize=(11, 8), num=NAME, tight_layout=True)
for (a, b) in bands:
    ax[0, 0].axvspan(a / 1e6, b / 1e6, color="tab:blue", alpha=0.08)
ax[0, 0].plot(f / 1e6, s11_dB, "k-", lw=2); ax[0, 0].axhline(-10, color="gray", ls="--")
ax[0, 0].set(xlabel="Frequency (MHz)", ylabel="S11 (dB)", title="Input matching"); ax[0, 0].grid()
ax[0, 1].plot(f / 1e6, Zin.real, "k-", lw=2, label="Re Zin"); ax[0, 1].plot(f / 1e6, Zin.imag, "r--", lw=2, label="Im Zin")
ax[0, 1].set(xlabel="Frequency (MHz)", ylabel="Zin (Ohm)", title="Input impedance"); ax[0, 1].grid(); ax[0, 1].legend()
ax[1, 0].remove(); pa = fig.add_subplot(2, 2, 3, projection="polar")
pa.plot(np.deg2rad(theta), gain_cut[:, 0], "k-", lw=2, label="xz-plane (phi=0)")
pa.plot(np.deg2rad(theta), gain_cut[:, 1], "r--", lw=2, label="yz-plane (phi=90)")
pa.set_theta_zero_location("N"); pa.set_theta_direction(-1); pa.set_rlim(np.max(gain_cut) - 30, np.max(gain_cut) + 1)
pa.set_title(f"Directivity (dBi) at {f_design/1e6:.1f} MHz"); pa.legend(loc="lower right", fontsize=8)
ax[1, 1].remove(); pb = fig.add_subplot(2, 2, 4, projection="polar")
pb.plot(np.deg2rad(np.arange(0.0, 360.5, 2.0)), gain_az, "b-", lw=2)
pb.set_rlim(np.max(gain_cut) - 30, np.max(gain_cut) + 1); pb.set_title("xy-plane (theta=90)")
fig.savefig(OUT + "_results.png", dpi=110)
if "--no-show" not in sys.argv:
    plt.show()
`;
}

function minFeature(p: Pcb): number {
  const m = minCopperFeature(p);
  return Number.isFinite(m) ? m : p.h;
}
